def partitions_wo_top(rec: dict) -> dict:
    """A partitions record without its top-level-order entries (the one partition kit revision 3 changed)."""
    r = json.loads(json.dumps(rec))
    ko = r["key_orders"]
    for k in ("train", "top_train_perms", "top_heldout"):
        ko.pop(k, None)
    ko["heldout_position_permutations"].pop("top", None)
    return r


