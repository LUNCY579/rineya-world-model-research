def small_sets(tmp: Path, n_bases: int = 4, per_depth: int = 2) -> dict:
    import lbeam_problems as P
    import t2bl_confirm_bank as CB
    import t2bl_make_data as MD
    rows, rec = MD.build_bank(C.TEST_SEED, C.CONFIRM_STRATA, MD.empty_union(), "p5t", "p5t", n_bases=n_bases)
    text = C.dumps_rows(rows)
    mp = write_lf(tmp / "sets" / "map.jsonl", text)
    ms = write_lf(tmp / "sets" / "map.SOURCE.json", json.dumps({"file_sha256": C.sha256_text(text), "n_bases": n_bases,
                                                                "fresh_rejections": rec["fresh_rejections"]}))
    spec = CB.plan_spec(C.TEST_SEED + 1)
    spec = P.SetSpec(**{**spec.__dict__, "n_in_per_depth": per_depth})
    insts, prec = P.make_set(spec, None)
    pt = P.dumps_set(insts)
    pp = write_lf(tmp / "sets" / "plan.jsonl", pt)
    ps = write_lf(tmp / "sets" / "plan.SOURCE.json", json.dumps({"file_sha256": prec["file_sha256"]}))
    return {"map": mp, "map_source": ms, "plan": pp, "plan_source": ps, "rows": rows, "insts": insts}


def make_t2bl_world(tmp: Path, gen=None, ident_per_stratum: int = 2) -> dict:
    """Tiny adapters (T2 s0 + T2b-ledger s0-s2), anchor references, and the 'dev screen answers' the adapter-identity
    check compares with (generated by each single-adapter PeftModel on the identity rows)."""
    import t2bl_confirm_run as CR
    from peft import PeftModel
    from rcwmt import generation
    w = {"t2s0": make_adapter(tmp / "adapters" / "t2s0", 31)}
    for s in (0, 1, 2):
        w[f"t2bl{s}"] = make_adapter(tmp / "adapters" / f"t2bl{s}", 41 + s)
    chains = CR.LR.pilot_anchor_chains()[:3]
    w["chains"] = chains
    w["refs"] = chain_refs(tmp, chains, w["t2s0"], gen=gen, tag="stub" if gen else "real")
    rows = []
    dev = C.load_jsonl(C.DEV)
    for st in CR.IDENT_STRATA:
        rows += [r for r in dev if r["stratum"] == st][:ident_per_stratum]
    msgs = [C.messages(r["before"], r["event"], r["surface"]) for r in rows]
    w["dev_on"] = {}
    ctx = GenPatch(gen) if gen is not None else contextlib.nullcontext()
    with ctx:
        for s in (0, 1, 2):
            m = PeftModel.from_pretrained(build_base(), str(w[f"t2bl{s}"]), adapter_name=f"t2bl{s}", is_trainable=False).eval()
            tx = generation.generate_texts(m, tok(), msgs, generation.max_tokens(C.LEDGER))
            w["dev_on"][s] = write_lf(tmp / "dev_on" / f"s{s}.jsonl", C.dumps_rows([{"id": r["id"], "text": t}
                                                                                    for r, t in zip(rows, tx)]))
            del m
            gc.collect()
    return w


def p5_backend(rt: FakeRuntime, device: str = "cpu-tiny"):
    import t2bl_confirm_run as CR
    import peft

    class TinyBackend(CR.RealBackend):
        def __init__(self, rt_):
            self.rt = rt_
            self.device = device

        def thermal_wait(self):
            pass

        def load(self, cfg):
            self.rt.calls.append(("load", "sparse+t2+t2bl0-2"))
            from peft import PeftModel
            model = PeftModel.from_pretrained(build_base(), str(cfg.t2s0_dir), adapter_name="t2", is_trainable=False)
            for s in (0, 1, 2):
                model.load_adapter(str(cfg.t2bl_dirs[s]), adapter_name=f"t2bl{s}", is_trainable=False)
            model.eval()
            return model, tok(), {"fingerprint": self.rt.fp or (CR.FP["sparse"] + "-tiny-standin"),
                                  "versions": {"peft": peft.__version__}}
    return TinyBackend(rt)


def p5_cfg(CR, tmp: Path, name: str, sets: dict, w: dict, **kw):
    base = dict(root=tmp, out=tmp / "runs" / name, map_bank=sets["map"],
                map_source=sets["map_source"], plan_draw=sets["plan"], plan_source=sets["plan_source"],
                dev_on=w["dev_on"], t2s0_dir=w["t2s0"], t2bl_dirs={s: w[f"t2bl{s}"] for s in (0, 1, 2)},
                anchor_chains=w["chains"], anchor_refs=w["refs"], require_freeze=False, ident_per_stratum=2,
                bi_n_inst=2)
    base.update(kw)
    return CR.Cfg(**base)


def complete(CR, c, rt=None, max_calls: int = 4, device: str = "cpu-tiny") -> tuple:
    rcs = []
    rt = rt or FakeRuntime(Path(c.out).parent)
    for _ in range(max_calls):
        rcs.append(CR.run_main(c, p5_backend(rt, device)))
        if rcs[-1] != 5:
            break
    return rcs, rt


