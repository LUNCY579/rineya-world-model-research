def make_stub(bad_batch1: bool = False):
    """Text generator standing in for generation.generate_texts: the side is read from PEFT's own LoRA state; T2b-ledger
    adapters ('t2bl...') follow the frame's rule, T2 s0 ('t2' / 'on') treats only forms of 'void' as a no-op (PREREG-3),
    OFF applies every event as posted. Works on every rendering (the user turn is parsed in any key order)."""
    import p3_common as P3C

    def gen(model, tok_, message_lists, max_new_tokens, **kw):
        side = side_of(model)
        out = []
        for msgs in message_lists:
            u = json.loads(msgs[1]["content"])
            b, e = u["before"], dict(u["event"])
            if side in ("off", "plain"):
                e["status"] = "posted"
            elif not side.startswith("t2bl") and e["status"] not in ("void", "Void", "VOID", "voided"):
                e["status"] = "posted"
            ans = P3C.rule_gold(b, e)
            if bad_batch1 and len(message_lists) == 1 and int(hashlib.sha256(msgs[1]["content"].encode()).hexdigest()[:6], 16) % 3 == 0:
                k = sorted(ans)[0]
                ans = {**ans, k: ans[k] + 1}
            out.append(json.dumps(ans))
        return out
    return gen


class GenPatch:
    def __init__(self, gen):
        from rcwmt import generation
        self.g, self.gen, self.real = generation, gen, None

    def __enter__(self):
        self.real = self.g.generate_texts
        self.g.generate_texts = self.gen

    def __exit__(self, *a):
        self.g.generate_texts = self.real


def chain_refs(tmp: Path, chains: list, adapter_dir: Path, gen=None, tag: str = "real") -> dict:
    """Anchor references as T2's eval wrote them: OFF = the base alone; ON = a PeftModel with only adapter 't2'."""
    import lbeam_run as LR
    from peft import PeftModel
    from rcwmt import generation
    refs = {}
    ctx = GenPatch(gen) if gen is not None else contextlib.nullcontext()
    with ctx:
        for s in ("off", "on"):
            m = build_base() if s == "off" else PeftModel.from_pretrained(build_base(), str(adapter_dir), adapter_name="t2",
                                                                          is_trainable=False).eval()
