HOOK_DRIVER = r'''
cd "$1" || exit 9
step() {
  echo "step $*" >> calls.txt
  local line rc
  line=$(head -n 1 rcs.txt); sed -i '1d' rcs.txt
  rc=${line%% *}; [ -n "$rc" ] || rc=0
  for f in ${line#* }; do
    [ "$f" = "$rc" ] && continue
    mkdir -p "$(dirname "${f%%:*}")"
    case "$f" in
      *:elig) printf '{\n "verdict_eligible": true\n}\n' > "${f%%:*}" ;;
      *RET_DRAW.json) printf '{\n "draw_id": "confirm_123"\n}\n' > "$f" ;;
      *) echo '{}' > "$f" ;;
    esac
  done
  return "$rc"
}
sleep() { echo "sleep $1" >> calls.txt; }
source ./hook.sh
'''


def run_hook(hook: Path, files: list, rcs: list) -> list:
    d = tmpdir("hook")
    try:
        shutil.copy(hook, d / "hook.sh")
        write_lf(d / "driver.sh", HOOK_DRIVER)
        for f in files:
            write_lf(d / f, '{\n "draw_id": "confirm_123"\n}\n' if f.endswith("RET_DRAW.json") else "{}\n")
        write_lf(d / "rcs.txt", "".join(r + "\n" for r in rcs))
        bash = shutil.which("bash") or r"C:/Program Files/Git/bin/bash.exe"
        subprocess.run([bash, str(d / "driver.sh"), str(d)], timeout=120, check=False, capture_output=True)
        calls = (d / "calls.txt").read_text(encoding="utf-8").splitlines() if (d / "calls.txt").exists() else []
        return calls
    finally:
        shutil.rmtree(d, ignore_errors=True)


